export function getAllCurrencies() {
  const pinned = ["PKR", "USD"];
  const rest = Object.keys(currencyRates).filter(c => !pinned.includes(c)).sort();
  return [...pinned, ...rest];
}

export function convertPrice(usd, toCurrency) {
  const rate = currencyRates[toCurrency] ?? 1;
  return Math.round(usd * rate);
}

export function formatPrice(usd, currency) {
  const meta = currencyMeta[currency] || { symbol: currency, name: currency };
  const converted = convertPrice(usd, currency);
  // locale formatting
  const formatted = converted.toLocaleString(currency === "PKR" ? "en-PK" : "en-US");
  return `${meta.symbol} ${formatted}`;
}
